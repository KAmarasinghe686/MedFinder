const seedData = async () => {
  await Pharmacy.bulkWrite(
    PHARMACY_SEED.map((pharmacy) => ({
      updateOne: {
        filter: { name: pharmacy.name },
        update: { $setOnInsert: pharmacy },
        upsert: true,
      },
    })),
  );

  const pharmacies = await Pharmacy.find({
    name: { $in: PHARMACY_SEED.map((pharmacy) => pharmacy.name) },
  }).lean();
  const pharmacyMap = new Map(
    pharmacies.map((pharmacy) => [pharmacy.name, pharmacy._id]),
  );

  const medicineOperations = MEDICINE_SEED
    .map((medicine) => {
      const pharmacyId = pharmacyMap.get(medicine.pharmacyName);
      if (!pharmacyId) {
        return null;
      }

      return {
        updateOne: {
          filter: {
            name: medicine.name,
            pharmacyName: medicine.pharmacyName,
          },
          update: {
            $setOnInsert: {
              ...medicine,
              pharmacyId,
            },
          },
          upsert: true,
        },
      };
    })
    .filter(Boolean);

  if (medicineOperations.length > 0) {
    await Medicine.bulkWrite(medicineOperations);

    const enrichmentFields = [
      'image',
      'productForm',
      'size',
      'description',
      'dose',
      'ingredients',
      'ageLimit',
    ];
    const enrichmentOperations = MEDICINE_SEED.flatMap((medicine) => {
      const operations = enrichmentFields
        .filter((field) => medicine[field])
        .map((field) => ({
          updateOne: {
            filter: {
              name: medicine.name,
              pharmacyName: medicine.pharmacyName,
              $or: [
                { [field]: { $exists: false } },
                { [field]: '' },
              ],
            },
            update: { $set: { [field]: medicine[field] } },
          },
        }));

      if (medicine.requiresPrescription) {
        operations.push({
          updateOne: {
            filter: {
              name: medicine.name,
              pharmacyName: medicine.pharmacyName,
              requiresPrescription: { $ne: true },
            },
            update: { $set: { requiresPrescription: true } },
          },
        });
      }

      return operations;
    });

    if (enrichmentOperations.length > 0) {
      await Medicine.bulkWrite(enrichmentOperations);
    }
  }
};

